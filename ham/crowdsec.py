def _version():
    if not installed():
        return ""
    try:
        r = subprocess.run([str(CROWDSEC_BIN), "-V"], capture_output=True, text=True, timeout=5)
        m = re.search(r"v?(\d+\.\d+\.\d+)", r.stdout + r.stderr)
        return m.group(1) if m else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def status(cfg):
    return {"installed": installed(), "version": _version(),
            "service": service_state() if installed() else "missing",
            "active": active(cfg), "configured": configured(cfg), "appsec": appsec_on(cfg), "listen": LISTEN,
            "bouncer_config": str(CROWDSEC_BOUNCER_CFG)}


@app.route("/api/crowdsec/settings", methods=["GET", "PUT"])
def api_crowdsec_settings():
    if request.method == "GET":
        cfg = load_config()
        s = settings_of(cfg)
        out = {k: v for k, v in s.items() if k not in ("api_key", "captcha_secret_key", "captcha_signing_key")}
        out["has_api_key"] = bool(api_key_of(cfg))
        out["has_captcha_secret"] = bool(s.get("captcha_secret_key"))
        out["status"] = status(cfg)
        return jsonify(out)
    body = request.get_json(force=True) or {}
    with _lock:
        cfg = load_config()
        cur = settings_of(cfg)
        new = dict(cur)
        for k in ("enabled", "insecure_skip_verify", "appsec_reject_large"):
            if k in body:
                new[k] = bool(body[k])
        for k in ("api_url", "mode", "captcha_provider", "captcha_site_key", "contact_url", "appsec_url"):
            if k in body:
                new[k] = (body.get(k) or "").strip() if isinstance(body.get(k), str) else ""
        # A secret left empty keeps the stored one: it cannot be read back.
        for k in ("api_key", "captcha_secret_key"):
            if isinstance(body.get(k), str) and body[k].strip():
                new[k] = body[k].strip()
        if isinstance(body.get("skip_lists"), list):
            new["skip_lists"] = access.known_lists(cfg, body["skip_lists"])
        if new.get("mode") == "captcha" and not new.get("captcha_signing_key"):
            new["captcha_signing_key"] = secrets.token_hex(32)
        try:
            check(new, cfg)
        except ValueError as e:
            return jsonify({"error": "These settings were not saved.\n\n" + str(e)}), 400
        draft = copy.deepcopy(cfg)
        draft["crowdsec"] = new
        from . import apply   # here, not at the top: apply imports this module
        ok, message = apply.check_rendered(draft)
        if not ok:
            return jsonify({"error": "These settings were not saved -- they do not produce a "
                                     "working configuration.\n\n" + message}), 400
        cfg["crowdsec"] = new
        save_config(cfg)
        return jsonify({"ok": True, "status": status(cfg)})


def _own_interface(url):
    """Does this address lead to haproxy-manager's own interface on this node:
    its port, on the loopback or on one of the node's addresses. CrowdSec's
    LAPI wants port 8080 by default, and so does this interface, so a LAPI
    installed on the node is the usual way to end up here."""
    try:
        parts = urlsplit(url)
        host, port = parts.hostname or "", parts.port or (443 if parts.scheme == "https" else 80)
    except ValueError:
        return False
    if not host or port != PORT:
        return False
    try:
        ips = {ai[4][0] for ai in socket.getaddrinfo(host, None)}
    except (OSError, UnicodeError):
        return False
    try:
        from . import apply
        own = {a.split("/")[0] for i in apply.node_interfaces() for a in i["addresses"]}
    except Exception:
        own = set()
    for ip in ips:
        try:
            if ip in own or ipaddress.ip_address(ip.split("%")[0]).is_loopback:
                return True
        except ValueError:
            pass
    return False


def _not_a_lapi(url, status):
    """What to say when something answers at the LAPI's address, and it is not the LAPI."""
    if _own_interface(url):
        text = "that address is haproxy-manager's own interface on this node, not CrowdSec (it answered %d)." % status
        if PORT == 8080:
            text += (" CrowdSec's LAPI wants port 8080 as well, so on this machine it needs another: "
                     "set listen_uri in /etc/crowdsec/config.yaml and url in "
                     "/etc/crowdsec/local_api_credentials.yaml to 127.0.0.1:8081, say, restart CrowdSec, "
                     "and give that port here.")
        return text
    if status == 404:
        return "the LAPI answered 404: something listens at that address, but it is not a CrowdSec LAPI"
    return "the LAPI answered %d" % status


@app.post("/api/crowdsec/test")
def api_crowdsec_test():
    """Ask the LAPI one question with these credentials, and say what came back."""
    body = request.get_json(force=True, silent=True) or {}
    cfg = load_config()
    stored_url = (settings_of(cfg).get("api_url") or "").strip().rstrip("/")
    url = (body.get("api_url") or stored_url).strip().rstrip("/")
    # The stored key goes only to the stored address: typed elsewhere, it
    # would hand the key to whoever answers there.
    key = (body.get("api_key") or "").strip() or (api_key_of(cfg) if url == stored_url else "")
    if not url or not key:
        return jsonify({"ok": False, "message": "a LAPI URL and an API key are needed first"})
    if _requests is None:
        return jsonify({"ok": False, "message": "python3-requests is not installed on this node"})
    try:
        r = _requests.get(url + "/v1/decisions", params={"ip": "192.0.2.1"},
                          headers={"X-Api-Key": key}, timeout=5,
                          verify=not body.get("insecure_skip_verify", settings_of(cfg).get("insecure_skip_verify")))
    except Exception as e:
        return jsonify({"ok": False, "message": "the LAPI did not answer: %s" % e})
    if r.status_code == 403:
        return jsonify({"ok": False, "message": "the LAPI refused the API key (403)"})
    if r.status_code != 200:
        return jsonify({"ok": False, "message": _not_a_lapi(url, r.status_code)})
    return jsonify({"ok": True, "message": "the LAPI answers and accepts the key"})


def _same_host(a, b):
    try:
        ha, hb = urlsplit(a).hostname, urlsplit(b).hostname
    except ValueError:
        return False
    return bool(ha) and (ha or "").lower() == (hb or "").lower()


@app.post("/api/crowdsec/test-appsec")
def api_crowdsec_test_appsec():
    """Ask AppSec about one harmless request, the way the bouncer would, from
    this node -- which is where the bouncer will ask from."""
    body = request.get_json(force=True, silent=True) or {}
    cfg = load_config()
    s = settings_of(cfg)
    stored_url = appsec_url_of(cfg).rstrip("/")
    typed = body.get("appsec_url")
    url = (typed if isinstance(typed, str) else stored_url).strip().rstrip("/")
    if not url:
        return jsonify({"ok": False, "message": "an AppSec URL is needed first"})
    if not re.match(r"^https?://[^\s/]+", url):
        return jsonify({"ok": False, "message": "the AppSec URL must start with http:// or https://, "
                                                "e.g. http://192.168.1.5:7422/"})
    # The stored key goes where it already goes: the stored AppSec address,
    # or the machine the LAPI is on. Anywhere else needs a key typed.
    key = (body.get("api_key") or "").strip() if isinstance(body.get("api_key"), str) else ""
    if not key and (url == stored_url or _same_host(url, (s.get("api_url") or "").strip())):
        key = api_key_of(cfg)
    if not key:
        return jsonify({"ok": False, "message": "an API key is needed first: the stored one is only sent "
                                                "to the stored AppSec URL or to the LAPI's own host"})
    if _requests is None:
        return jsonify({"ok": False, "message": "python3-requests is not installed on this node"})
    try:
        # Certificates are verified whatever the LAPI setting says: the
        # bouncer has no way to skip that for AppSec, so neither does this.
        r = _requests.get(url + "/", timeout=5, allow_redirects=False, headers={
            "X-Crowdsec-Appsec-Ip": "192.0.2.1", "X-Crowdsec-Appsec-Uri": "/",
            "X-Crowdsec-Appsec-Host": "haproxy-manager.invalid", "X-Crowdsec-Appsec-Verb": "GET",
            "X-Crowdsec-Appsec-Api-Key": key, "X-Crowdsec-Appsec-User-Agent": "haproxy-manager",
            "X-Crowdsec-Appsec-Http-Version": "11", "User-Agent": "haproxy-manager"})
    except Exception as e:
        return jsonify({"ok": False, "message": "AppSec did not answer: %s" % e})
    if r.status_code == 401:
        return jsonify({"ok": False, "message": "AppSec refused the API key (401)"})
    if r.status_code not in (200, 403):
        return jsonify({"ok": False, "message": "AppSec answered %d" % r.status_code})
    return jsonify({"ok": True, "message": "AppSec answers and accepts the key"})


# The repository the package comes from. Its Debian 13 suite is empty at the
# time of writing; the bookworm build is a static Go binary with one trivial
# dependency and installs on anything newer, which is what the image does too.
# The signing key is fetched over HTTPS and then held to this fingerprint,
# so a wrong key -- a changed one, a redirected fetch -- installs nothing.
REPO_KEY_URL = "https://packagecloud.io/crowdsec/crowdsec/gpgkey"
REPO_KEY_FPR = "6A89E3C2303A901A889971D3376ED5326E93CD0C"
REPO_LINE = ("deb [signed-by=/etc/apt/keyrings/crowdsec.gpg] "
             "https://packagecloud.io/crowdsec/crowdsec/debian/ bookworm main\n")
APT_INSTALL = """set -e
export DEBIAN_FRONTEND=noninteractive
command -v gpg >/dev/null || apt-get -o DPkg::Lock::Timeout=120 install -y --no-install-recommends gnupg
mkdir -p /etc/apt/keyrings
curl -fsSL --max-time 60 %(key)s | gpg --dearmor --yes -o /etc/apt/keyrings/crowdsec.gpg
gpg --show-keys --with-colons /etc/apt/keyrings/crowdsec.gpg | grep -q '^fpr:::::::::%(fpr)s:' || { echo "CrowdSec's key does not match the expected fingerprint"; rm -f /etc/apt/keyrings/crowdsec.gpg; exit 1; }
printf '%%s' '%(line)s' > /etc/apt/sources.list.d/crowdsec.list
# a minimised system drops /usr/share/doc, and the bouncer's post-install copies
# a file from there; without it the package stays half-configured
[ -d /etc/dpkg/dpkg.cfg.d ] && echo "path-include /usr/share/doc/crowdsec-haproxy-spoa-bouncer/*" > /etc/dpkg/dpkg.cfg.d/zz-crowdsec
apt-get -o DPkg::Lock::Timeout=120 -o Acquire::http::Timeout=30 -o Acquire::Retries=2 update -q
apt-get -o DPkg::Lock::Timeout=120 -o Acquire::http::Timeout=30 -o Acquire::Retries=2 install -y --no-install-recommends crowdsec-haproxy-spoa-bouncer
systemctl disable --now crowdsec-spoa-bouncer >/dev/null 2>&1 || true
""" % {"key": REPO_KEY_URL, "fpr": REPO_KEY_FPR, "line": REPO_LINE}
# RPM systems get a repository file written here rather than CrowdSec's
# install script run from the network: el/<major> for the Enterprise Linux
# family, fedora/<version> for Fedora, and the same key check.
RPM_INSTALL = """set -e
. /etc/os-release
case "$ID" in
  fedora) suite="fedora/${VERSION_ID%%%%.*}" ;;
  *)      suite="el/${VERSION_ID%%%%.*}" ;;
esac
curl -fsSL --max-time 60 %(key)s -o /tmp/crowdsec.gpgkey
gpg --show-keys --with-colons /tmp/crowdsec.gpgkey | grep -q '^fpr:::::::::%(fpr)s:' || { echo "CrowdSec's key does not match the expected fingerprint"; rm -f /tmp/crowdsec.gpgkey; exit 1; }
rpm --import /tmp/crowdsec.gpgkey && rm -f /tmp/crowdsec.gpgkey
printf '%%s\\n' '[crowdsec_crowdsec]' 'name=crowdsec_crowdsec' "baseurl=https://packagecloud.io/crowdsec/crowdsec/$suite/\\$basearch" 'repo_gpgcheck=1' 'gpgcheck=0' 'enabled=1' 'gpgkey=%(key)s' 'sslverify=1' 'metadata_expire=300' > /etc/yum.repos.d/crowdsec_crowdsec.repo
if command -v dnf >/dev/null; then dnf install -y crowdsec-haproxy-spoa-bouncer; else yum install -y crowdsec-haproxy-spoa-bouncer; fi
systemctl disable --now crowdsec-spoa-bouncer >/dev/null 2>&1 || true
""" % {"key": REPO_KEY_URL, "fpr": REPO_KEY_FPR}


def install():
    """Put the bouncer on this node from CrowdSec's repository: (ok, output)."""
    if installed():
        return True, "the bouncer is already installed"
    if shutil.which("apt-get"):
        script = APT_INSTALL
    elif shutil.which("dnf") or shutil.which("yum"):
        script = RPM_INSTALL
    else:
        return False, ("this node has neither apt-get nor dnf; install crowdsec-haproxy-spoa-bouncer "
                       "from CrowdSec's repository by hand")
    rc, out = run_script(script, timeout=900)
    if rc != 0 or not installed():
        return False, "the install did not finish:\n" + (out or "").strip()[-1500:]
    return True, "installed; it starts when CrowdSec is on and Apply runs"


@app.post("/api/crowdsec/install")
def api_crowdsec_install():
    """Install the bouncer on this node, from CrowdSec's repository."""
    ok, message = install()
    if ok:
        NOT_WANTED.unlink(missing_ok=True)     # asked for by hand: wanted after all
        TRIED.unlink(missing_ok=True)
    return jsonify({"ok": ok, "message": message, "status": status(load_config())}), (200 if ok else 500)
