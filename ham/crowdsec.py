def global_lines(cfg):
    """Captcha pages are streamed through HAProxy's buffer, which the
    bouncer's documentation wants at 64 kB for them; a request body on its
    way to AppSec has to fit the same buffer, with the same answer."""
    if active(cfg) and (settings_of(cfg).get("mode") == "captcha" or appsec_on(cfg)):
        return ["tune.bufsize 65536"]
    return []


def _and(test, acl):
    """A rule's test with one more thing that must hold, in each of its
    alternatives: " if A || B" and "x" make " if A x || B x"."""
    if not test:
        return " if " + acl
    return " if " + " || ".join(alt + " " + acl for alt in test[len(" if "):].split(" || "))


def frontend_lines(cfg, src_acl, streams=()):
    """What an HTTP listener declares and does when CrowdSec is on:
    (declarations, requests). `src_acl(name, nets)` declares a source ACL
    the way the renderer does elsewhere. `streams` are the tests of this
    listener's routing rules for services that speak gRPC."""
    if not active(cfg):
        return [], []
    s = settings_of(cfg)
    decl = [
        "unique-id-format %[uuid()]",
        "filter spoe engine crowdsec config %s" % CROWDSEC_SPOE,
        "acl cs_ban var(txn.crowdsec.remediation) -m str ban",
        "acl cs_captcha var(txn.crowdsec.remediation) -m str captcha",
        # A browser gets a page; a script or an API client gets a line of text.
        "acl cs_html req.hdr_cnt(Accept) eq 0",
        "acl cs_html req.hdr(Accept) -m sub text/html",
        "acl cs_html req.hdr(Accept) -m sub */*",
        'acl cs_nohtml req.hdr(Accept) -m reg "text/html;q=0"',
    ]
    trusted, _bad = access.list_networks(cfg, s.get("skip_lists"))
    if trusted:
        decl += src_acl("cs_trusted", trusted)
    if appsec_on(cfg):
        # AppSec reads the body, so HAProxy has to hold the request until the
        # body is in -- or the buffer is full -- before it asks. One that fits
        # the frame travels with the question; a larger one cannot, and the
        # question goes without it. The bouncer's own example, with the
        # trusted networks left out of both.
        who = "!cs_trusted " if trusted else ""
        streams = [t for t in streams if not t or t.startswith(" if ")]
        decl.append("acl cs_body_fits req.body_size -m int le %d" % APPSEC_BODY_LIMIT)
        req = []
        if not streams:
            decl.insert(len(decl) - 1, "option http-buffer-request")
            live, quiet = "", ""
        else:
            # A gRPC stream is a request whose body never ends, and a listener
            # that waits for whole bodies never lets one through: the call
            # sits there until the client gives up (#37). So where a service
            # is marked as speaking gRPC -- HTTP/2 to its servers -- the
            # waiting is done per request instead, and that service's gRPC
            # requests are not made to wait. Only those: by content type on
            # any service, a visitor could switch the inspection off by
            # claiming to speak gRPC. Everything else waits exactly as the
            # option had it -- for the whole body, however slowly it comes --
            # and a stream is asked about without its body.
            decl += ["acl cs_grpc req.hdr(content-type) -m beg application/grpc",
                     "acl cs_stream var(txn.cs_stream) -m bool"]
            req += ["http-request set-var(txn.cs_stream) bool(1)" + _and(t, "cs_grpc") for t in streams]
            req.append("http-request wait-for-body time 24h unless cs_stream"
                       + (" || cs_trusted" if trusted else ""))
            live, quiet = "!cs_stream ", " || %scs_stream" % who
        if s.get("appsec_reject_large"):
            # Asked for: what AppSec cannot read does not reach the service.
            req.append('http-request return status 413 content-type text/plain string '
                       '"Request body too large to inspect\\n" if %s%s{ req.body_size -m found } !cs_body_fits' % (who, live))
        req += ["http-request send-spoe-group crowdsec crowdsec-http-body "
                "if %s%scs_body_fits || %s%s!{ req.body_size -m found }" % (who, live, who, live),
                "http-request send-spoe-group crowdsec crowdsec-http-no-body "
                "if %s!cs_body_fits { req.body_size -m found }%s" % (who, quiet)]
    else:
        req = ["http-request send-spoe-group crowdsec crowdsec-http-no-body"
               + (" unless cs_trusted" if trusted else "")]
    if s.get("mode") == "captcha":
        req += [
            # Solved: back to the page that was asked for.
            'http-request redirect code 302 location %[url] if { var(txn.crowdsec.remediation) -m str "allow" } { var(txn.crowdsec.redirect) -m found }',
            'http-request return status 200 content-type "text/html; charset=utf-8" hdr Cache-Control "no-cache, no-store" lf-file %s/captcha.html if cs_captcha cs_html !cs_nohtml' % CROWDSEC_HTML,
            'http-request return status 200 content-type text/plain hdr Cache-Control "no-cache, no-store" string "Captcha required\\n" if cs_captcha',
            "http-after-response set-header Set-Cookie %[var(txn.crowdsec.captcha_cookie)] if { var(txn.crowdsec.captcha_cookie) -m found }",
        ]
    # The ban page: this installation's own 403 page when it has one, else
    # the bouncer's, with the contact link when a contact URL is set.
    own = next((p for p in errorpages.everywhere(cfg) if 403 in _codes(p)), None)
    if own:
        page = "file %s" % errorpages.path(own, 403, "html")
    elif (s.get("contact_url") or "").strip():
        page = "lf-file %s/ban-with-contact.html" % CROWDSEC_HTML
    else:
        page = "lf-file %s/ban.html" % CROWDSEC_HTML
    req += [
        'http-request return status 403 content-type "text/html; charset=utf-8" hdr Cache-Control "no-cache, no-store" %s if cs_ban cs_html !cs_nohtml' % page,
        'http-request return status 403 content-type text/plain hdr Cache-Control "no-cache, no-store" string "Forbidden\\n" if cs_ban',
    ]
    return decl, req


def _codes(page):
    try:
        return errorpages.codes_of(page)
    except ValueError:
        return []


def backend_lines(cfg):
    """The agent HAProxy talks SPOE to: the bouncer on this node."""
    if not active(cfg):
        return []
    return ["backend crowdsec-spoa", "    mode tcp", "    timeout connect 2s",
            "    timeout server 60s", "    server spoa %s" % LISTEN, ""]


def summary(cfg):
    """For the status every page polls: on or off, and whether the bouncer runs."""
    on = configured(cfg)
    return {"on": on, "installed": installed(),
            "bouncer": service_state() if on and installed() else ("missing" if on else "off")}


