def global_lines(cfg):
    """Captcha pages are streamed through HAProxy's buffer, which the
    bouncer's documentation wants at 64 kB for them."""
    if active(cfg) and settings_of(cfg).get("mode") == "captcha":
        return ["tune.bufsize 65536"]
    return []


def frontend_lines(cfg, src_acl):
    """What an HTTP listener declares and does when CrowdSec is on:
    (declarations, requests). `src_acl(name, nets)` declares a source ACL
    the way the renderer does elsewhere."""
    if not active(cfg):
        return [], []
    s = settings_of(cfg)
    decl = [
        "unique-id-format %[uuid()]",
        "filter spoe engine crowdsec config %s" % CROWDSEC_SPOE,
        "acl cs_ban var(txn.crowdsec.remediation) -m str ban",
        "acl cs_captcha var(txn.crowdsec.remediation) -m str captcha",
        # A browser gets a page; a script or an API client gets a line of text.
        "acl cs_html req.hdr_cnt(Accept) eq 0",
        "acl cs_html req.hdr(Accept) -m sub text/html",
        "acl cs_html req.hdr(Accept) -m sub */*",
        'acl cs_nohtml req.hdr(Accept) -m reg "text/html;q=0"',
    ]
    trusted, _bad = access.list_networks(cfg, s.get("skip_lists"))
    ask = "http-request send-spoe-group crowdsec crowdsec-http-no-body"
    if trusted:
        decl += src_acl("cs_trusted", trusted)
        ask += " unless cs_trusted"
    req = [ask]
    if s.get("mode") == "captcha":
        req += [
            # Solved: back to the page that was asked for.
            'http-request redirect code 302 location %[url] if { var(txn.crowdsec.remediation) -m str "allow" } { var(txn.crowdsec.redirect) -m found }',
            'http-request return status 200 content-type "text/html; charset=utf-8" hdr Cache-Control "no-cache, no-store" lf-file %s/captcha.html if cs_captcha cs_html !cs_nohtml' % CROWDSEC_HTML,
            'http-request return status 200 content-type text/plain hdr Cache-Control "no-cache, no-store" string "Captcha required\\n" if cs_captcha',
            "http-after-response set-header Set-Cookie %[var(txn.crowdsec.captcha_cookie)] if { var(txn.crowdsec.captcha_cookie) -m found }",
        ]
    # The ban page: this installation's own 403 page when it has one, else
    # the bouncer's, with the contact link when a contact URL is set.
    own = next((p for p in errorpages.everywhere(cfg) if 403 in _codes(p)), None)
    if own:
        page = "file %s" % errorpages.path(own, 403, "html")
    elif (s.get("contact_url") or "").strip():
        page = "lf-file %s/ban-with-contact.html" % CROWDSEC_HTML
    else:
        page = "lf-file %s/ban.html" % CROWDSEC_HTML
    req += [
        'http-request return status 403 content-type "text/html; charset=utf-8" hdr Cache-Control "no-cache, no-store" %s if cs_ban cs_html !cs_nohtml' % page,
        'http-request return status 403 content-type text/plain hdr Cache-Control "no-cache, no-store" string "Forbidden\\n" if cs_ban',
    ]
    return decl, req


def _codes(page):
    try:
        return errorpages.codes_of(page)
    except ValueError:
        return []


def backend_lines(cfg):
    """The agent HAProxy talks SPOE to: the bouncer on this node."""
    if not active(cfg):
        return []
    return ["backend crowdsec-spoa", "    mode tcp", "    timeout connect 2s",
            "    timeout server 60s", "    server spoa %s" % LISTEN, ""]


def summary(cfg):
    """For the status every page polls: on or off, and whether the bouncer runs."""
    on = configured(cfg)
    return {"on": on, "installed": installed(),
            "bouncer": service_state() if on and installed() else ("missing" if on else "off")}


