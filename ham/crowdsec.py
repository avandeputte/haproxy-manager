"""CrowdSec: the bouncer beside HAProxy, and what HAProxy asks it.

CrowdSec decides who is banned from what its agents see across the fleet;
HAProxy asks about each visitor through SPOE -- a small protocol to a local
agent, the SPOA bouncer -- and acts on the answer: a ban page, a captcha, or
nothing. The bouncer runs on every node, polls the CrowdSec LAPI for
decisions and keeps them in memory. This module writes its configuration and
the SPOE file HAProxy reads, keeps the service running while CrowdSec is on,
and offers to install the package where it is not.

Fail-open, by design: a bouncer that is down or slow leaves the request's
remediation unset, and HAProxy serves the request. Protection that took a
service down whenever its helper hiccupped would be switched off the first
time it did.
"""

