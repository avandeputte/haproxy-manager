UNIT = "crowdsec-spoa-bouncer"
LISTEN = "127.0.0.1:9000"
PROVIDERS = ("hcaptcha", "recaptcha", "turnstile")
MODES = ("ban", "captcha")

# The SPOE engine HAProxy loads: what it sends the bouncer and when. The
# bouncer's own example, less the body message -- AppSec is not wired here, so
# no request body ever travels -- and with the backend named below.
SPOE = """# Generated by haproxy-manager -- do not edit by hand.
# The scope the listener names: filter spoe engine crowdsec config <this file>.
[crowdsec]
spoe-agent crowdsec-agent
    messages    crowdsec-tcp
    groups      crowdsec-http-no-body
    option      var-prefix      crowdsec
    option      set-on-error    error
    timeout     hello           200ms
    timeout     idle            55s
    timeout     processing      500ms
    use-backend crowdsec-spoa
    log         global

# Asked once per connection: the address alone, before any request.
spoe-message crowdsec-tcp
    args id=unique-id src-ip=src src-port=src_port
    event on-client-session

# Asked per request: the headers carry the host and the captcha cookie.
spoe-message crowdsec-http-no-body
    args remediation=var(txn.crowdsec.remediation) id=unique-id method=method path=path query=query version=req.ver headers=req.hdrs url=url ssl=ssl_fc src-ip=src src-port=src_port

spoe-group crowdsec-http-no-body
    messages    crowdsec-http-no-body
"""


def settings_of(cfg):
    out = dict(DEFAULT_CONFIG["crowdsec"])
    out.update(cfg.get("crowdsec") or {})
    return out


def api_key_of(cfg):
    """The key this node presents: its own, when it was given one, else the shared one."""
    local = (cfg.get("local") or {}).get("crowdsec") or {}
    return (local.get("api_key") or settings_of(cfg).get("api_key") or "").strip()


def configured(cfg):
    """Is CrowdSec meant to be running: switched on, and told where to ask."""
    s = settings_of(cfg)
    return bool(s.get("enabled") and (s.get("api_url") or "").strip() and api_key_of(cfg))


def installed():
    return CROWDSEC_BIN.exists()


def active(cfg):
    """Does HAProxy on this node ask: CrowdSec is wanted, and the bouncer is
    here to answer. A node without it renders no trace of CrowdSec -- lines
    naming pages it does not have would fail haproxy -c, and asking an agent
    that is not there would cost every request a refused connection. Apply
    says so instead."""
    return configured(cfg) and installed()


def check(settings, cfg):
    """Refuse settings that cannot work, with the reason. Raises ValueError."""
    if not settings.get("enabled"):
        return
    url = (settings.get("api_url") or "").strip()
    if not re.match(r"^https?://[^\s/]+", url):
        raise ValueError("the LAPI URL must start with http:// or https://, e.g. http://192.168.1.5:8080/")
    if not (settings.get("api_key") or api_key_of(cfg)):
        raise ValueError("the bouncer needs an API key: cscli bouncers add haproxy-manager on the CrowdSec host")
    if settings.get("mode") not in MODES:
        raise ValueError("the mode must be ban or captcha")
    if settings.get("mode") == "captcha":
        if settings.get("captcha_provider") not in PROVIDERS:
            raise ValueError("a captcha needs a provider: hcaptcha, recaptcha or turnstile")
        if not (settings.get("captcha_site_key") or "").strip() or not (settings.get("captcha_secret_key") or "").strip():
            raise ValueError("a captcha needs the provider's site key and secret key")


