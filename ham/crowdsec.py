def _version():
    if not installed():
        return ""
    try:
        r = subprocess.run([str(CROWDSEC_BIN), "-V"], capture_output=True, text=True, timeout=5)
        m = re.search(r"v?(\d+\.\d+\.\d+)", r.stdout + r.stderr)
        return m.group(1) if m else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def status(cfg):
    return {"installed": installed(), "version": _version(),
            "service": service_state() if installed() else "missing",
            "active": active(cfg), "configured": configured(cfg), "listen": LISTEN,
            "bouncer_config": str(CROWDSEC_BOUNCER_CFG)}


@app.route("/api/crowdsec/settings", methods=["GET", "PUT"])
def api_crowdsec_settings():
    if request.method == "GET":
        cfg = load_config()
        s = settings_of(cfg)
        out = {k: v for k, v in s.items() if k not in ("api_key", "captcha_secret_key", "captcha_signing_key")}
        out["has_api_key"] = bool(api_key_of(cfg))
        out["has_captcha_secret"] = bool(s.get("captcha_secret_key"))
        out["status"] = status(cfg)
        return jsonify(out)
    body = request.get_json(force=True) or {}
    with _lock:
        cfg = load_config()
        cur = settings_of(cfg)
        new = dict(cur)
        for k in ("enabled", "insecure_skip_verify"):
            if k in body:
                new[k] = bool(body[k])
        for k in ("api_url", "mode", "captcha_provider", "captcha_site_key", "contact_url"):
            if k in body:
                new[k] = (body.get(k) or "").strip() if isinstance(body.get(k), str) else ""
        # A secret left empty keeps the stored one: it cannot be read back.
        for k in ("api_key", "captcha_secret_key"):
            if isinstance(body.get(k), str) and body[k].strip():
                new[k] = body[k].strip()
        if isinstance(body.get("skip_lists"), list):
            new["skip_lists"] = access.known_lists(cfg, body["skip_lists"])
        if new.get("mode") == "captcha" and not new.get("captcha_signing_key"):
            new["captcha_signing_key"] = secrets.token_hex(32)
        try:
            check(new, cfg)
        except ValueError as e:
            return jsonify({"error": "These settings were not saved.\n\n" + str(e)}), 400
        draft = copy.deepcopy(cfg)
        draft["crowdsec"] = new
        from . import apply   # here, not at the top: apply imports this module
        ok, message = apply.check_rendered(draft)
        if not ok:
            return jsonify({"error": "These settings were not saved -- they do not produce a "
                                     "working configuration.\n\n" + message}), 400
        cfg["crowdsec"] = new
        save_config(cfg)
        return jsonify({"ok": True, "status": status(cfg)})


@app.post("/api/crowdsec/test")
def api_crowdsec_test():
    """Ask the LAPI one question with these credentials, and say what came back."""
    body = request.get_json(force=True, silent=True) or {}
    cfg = load_config()
    stored_url = (settings_of(cfg).get("api_url") or "").strip().rstrip("/")
    url = (body.get("api_url") or stored_url).strip().rstrip("/")
    # The stored key goes only to the stored address: typed elsewhere, it
    # would hand the key to whoever answers there.
    key = (body.get("api_key") or "").strip() or (api_key_of(cfg) if url == stored_url else "")
    if not url or not key:
        return jsonify({"ok": False, "message": "a LAPI URL and an API key are needed first"})
    if _requests is None:
        return jsonify({"ok": False, "message": "python3-requests is not installed on this node"})
    try:
        r = _requests.get(url + "/v1/decisions", params={"ip": "192.0.2.1"},
                          headers={"X-Api-Key": key}, timeout=5,
                          verify=not body.get("insecure_skip_verify", settings_of(cfg).get("insecure_skip_verify")))
    except Exception as e:
        return jsonify({"ok": False, "message": "the LAPI did not answer: %s" % e})
    if r.status_code == 403:
        return jsonify({"ok": False, "message": "the LAPI refused the API key (403)"})
    if r.status_code != 200:
        return jsonify({"ok": False, "message": "the LAPI answered %d" % r.status_code})
    return jsonify({"ok": True, "message": "the LAPI answers and accepts the key"})


